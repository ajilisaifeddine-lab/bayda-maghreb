const fs = require('fs');
const path = require('path');

const packagesDir = path.join(__dirname, '../packages');
const outKeywordsPath = path.join(__dirname, '../apps/web-lab/dialects.ts');
const outVocabPath = path.join(__dirname, '../apps/web-lab/vocabularies.ts');

let keywordsOutput = `// Auto-generated by build-dialects.cjs\n\n`;
let vocabOutput = `// Auto-generated by build-dialects.cjs\n\n`;

const dirs = fs.readdirSync(packagesDir).filter(f => fs.statSync(path.join(packagesDir, f)).isDirectory());

dirs.forEach(dir => {
  const varName = dir.replace(/-/g, '_');
  
  // 1. Process Keywords
  const kwPath = path.join(packagesDir, dir, 'keywords.json');
  if (fs.existsSync(kwPath)) {
    const content = fs.readFileSync(kwPath, 'utf8');
    keywordsOutput += `export const ${varName}_kw = ${content};\n\n`;
  }

  // 2. Process Vocabulary
  const vocabPath = path.join(packagesDir, dir, 'vocabulary.json');
  if (fs.existsSync(vocabPath)) {
    const content = fs.readFileSync(vocabPath, 'utf8');
    vocabOutput += `export const ${varName}_vocab = ${content};\n\n`;
  }
});

keywordsOutput += `export const allKeywords: Record<string, any> = {\n`;
vocabOutput += `export const allVocabularies: Record<string, any> = {\n`;

dirs.forEach(dir => {
  const varName = dir.replace(/-/g, '_');
  if (fs.existsSync(path.join(packagesDir, dir, 'keywords.json'))) {
    keywordsOutput += `  '${dir}': ${varName}_kw,\n`;
  }
  if (fs.existsSync(path.join(packagesDir, dir, 'vocabulary.json'))) {
    vocabOutput += `  '${dir}': ${varName}_vocab,\n`;
  }
});

keywordsOutput += `};\n`;
vocabOutput += `};\n`;

fs.writeFileSync(outKeywordsPath, keywordsOutput, 'utf8');
fs.writeFileSync(outVocabPath, vocabOutput, 'utf8');
console.log('✅ Successfully generated dialects.ts and vocabularies.ts!');
